import Foundation
import CoreGraphics

/// 5x7 glyph bitmaps (HD44780 lineage). The flock uses these as formation
/// targets when it spells the current track title out of its own bodies.
enum DotMatrixFont {
    /// 5 column bytes per glyph, LSB = top row, 7 rows used.
    static let glyphs: [Character: [UInt8]] = [
        "A": [0x7E, 0x11, 0x11, 0x11, 0x7E], "B": [0x7F, 0x49, 0x49, 0x49, 0x36],
        "C": [0x3E, 0x41, 0x41, 0x41, 0x22], "D": [0x7F, 0x41, 0x41, 0x22, 0x1C],
        "E": [0x7F, 0x49, 0x49, 0x49, 0x41], "F": [0x7F, 0x09, 0x09, 0x09, 0x01],
        "G": [0x3E, 0x41, 0x49, 0x49, 0x7A], "H": [0x7F, 0x08, 0x08, 0x08, 0x7F],
        "I": [0x00, 0x41, 0x7F, 0x41, 0x00], "J": [0x20, 0x40, 0x41, 0x3F, 0x01],
        "K": [0x7F, 0x08, 0x14, 0x22, 0x41], "L": [0x7F, 0x40, 0x40, 0x40, 0x40],
        "M": [0x7F, 0x02, 0x0C, 0x02, 0x7F], "N": [0x7F, 0x04, 0x08, 0x10, 0x7F],
        "O": [0x3E, 0x41, 0x41, 0x41, 0x3E], "P": [0x7F, 0x09, 0x09, 0x09, 0x06],
        "Q": [0x3E, 0x41, 0x51, 0x21, 0x5E], "R": [0x7F, 0x09, 0x19, 0x29, 0x46],
        "S": [0x46, 0x49, 0x49, 0x49, 0x31], "T": [0x01, 0x01, 0x7F, 0x01, 0x01],
        "U": [0x3F, 0x40, 0x40, 0x40, 0x3F], "V": [0x1F, 0x20, 0x40, 0x20, 0x1F],
        "W": [0x3F, 0x40, 0x38, 0x40, 0x3F], "X": [0x63, 0x14, 0x08, 0x14, 0x63],
        "Y": [0x07, 0x08, 0x70, 0x08, 0x07], "Z": [0x61, 0x51, 0x49, 0x45, 0x43],
        "0": [0x3E, 0x51, 0x49, 0x45, 0x3E], "1": [0x00, 0x42, 0x7F, 0x40, 0x00],
        "2": [0x42, 0x61, 0x51, 0x49, 0x46], "3": [0x21, 0x41, 0x45, 0x4B, 0x31],
        "4": [0x18, 0x14, 0x12, 0x7F, 0x10], "5": [0x27, 0x45, 0x45, 0x45, 0x39],
        "6": [0x3C, 0x4A, 0x49, 0x49, 0x30], "7": [0x01, 0x71, 0x09, 0x05, 0x03],
        "8": [0x36, 0x49, 0x49, 0x49, 0x36], "9": [0x06, 0x49, 0x49, 0x29, 0x1E],
        " ": [0x00, 0x00, 0x00, 0x00, 0x00], "-": [0x08, 0x08, 0x08, 0x08, 0x08],
        "+": [0x08, 0x08, 0x3E, 0x08, 0x08], ".": [0x00, 0x60, 0x60, 0x00, 0x00],
        ",": [0x00, 0x50, 0x30, 0x00, 0x00], "'": [0x00, 0x05, 0x03, 0x00, 0x00],
        "!": [0x00, 0x00, 0x5F, 0x00, 0x00], "?": [0x02, 0x01, 0x51, 0x09, 0x06],
        "(": [0x00, 0x1C, 0x22, 0x41, 0x00], ")": [0x00, 0x41, 0x22, 0x1C, 0x00],
        "/": [0x20, 0x10, 0x08, 0x04, 0x02], ":": [0x00, 0x36, 0x36, 0x00, 0x00],
        "&": [0x36, 0x49, 0x55, 0x22, 0x50], "#": [0x14, 0x7F, 0x14, 0x7F, 0x14],
    ]

    static func columns(for text: String) -> [UInt8] {
        var out: [UInt8] = []
        for ch in text.uppercased() {
            out += glyphs[ch] ?? glyphs["?"]!
            out.append(0x00) // inter-character gap column
        }
        return out
    }

    /// The lit-dot positions for `text`, in glyph-grid units (x = column,
    /// y = row 0-6). The flock scales these into screen space.
    static func dotPositions(for text: String) -> [CGPoint] {
        var points: [CGPoint] = []
        for (columnIndex, column) in columns(for: text).enumerated() {
            for row in 0..<7 where (column >> UInt8(row)) & 1 == 1 {
                points.append(CGPoint(x: CGFloat(columnIndex), y: CGFloat(row)))
            }
        }
        return points
    }
}
